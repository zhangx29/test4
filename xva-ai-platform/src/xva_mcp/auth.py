"""Validate OAuth access tokens from the bank's identity provider (e.g. Microsoft Entra ID).

The MCP server acts only as a resource server: it checks signature, issuer, audience, expiry and,
optionally, which client application obtained the token; then it hands the claims to
entitlements.py. It never forwards the user's token to downstream systems (the MCP spec forbids
token passthrough); the server reads the curated store with its own read-only service identity.

Several front ends can call the same server, each with its own token audience:
  - VS Code / GitHub Copilot: the API's own audience (with v2 Entra tokens, usually its client ID).
  - Microsoft 365 Copilot (Entra SSO): additionally the Application ID URI generated by the SSO
    registration; Microsoft documents that the server must accept it as an audience, and that tokens
    come from the Microsoft Enterprise token store client (ab3be6b7-f5df-413d-ac2d-abf1e3fd9c0b).
  - Copilot Studio (custom connector, on-behalf-of): the API's audience; the client is the connector's
    own app registration.
So issuers, audiences and allowed client IDs are all lists.
"""

from __future__ import annotations

from typing import Any, Iterable

from mcp.server.auth.provider import AccessToken, TokenVerifier

# Client ID of the Microsoft Enterprise token store that M365 Copilot uses for Entra SSO plugins.
M365_COPILOT_TOKEN_STORE_CLIENT_ID = "ab3be6b7-f5df-413d-ac2d-abf1e3fd9c0b"


def split_list(value: str | Iterable[str] | None) -> list[str]:
    """Accept 'a, b' strings (from environment variables) or iterables; drop blanks."""
    if value is None:
        return []
    items = value.split(",") if isinstance(value, str) else list(value)
    return [item.strip() for item in items if item and item.strip()]


class JwtTokenVerifier(TokenVerifier):
    def __init__(
        self,
        issuers: str | Iterable[str],
        audiences: str | Iterable[str],
        jwks_url: str,
        allowed_client_ids: str | Iterable[str] | None = None,
        algorithms: tuple[str, ...] = ("RS256",),
    ):
        import jwt  # pyjwt[crypto]; optional dependency group "auth"

        self._jwt = jwt
        self.issuers = split_list(issuers)
        self.audiences = split_list(audiences)
        if not self.issuers or not self.audiences:
            raise ValueError("At least one issuer and one audience are required")
        allowed = split_list(allowed_client_ids)
        self.allowed_client_ids = set(allowed) if allowed else None  # None = any client
        self.algorithms = list(algorithms)
        self._jwks = jwt.PyJWKClient(jwks_url, cache_keys=True)

    def _signing_key(self, token: str) -> Any:
        return self._jwks.get_signing_key_from_jwt(token).key

    async def verify_token(self, token: str) -> AccessToken | None:
        jwt = self._jwt
        try:
            claims = jwt.decode(
                token,
                self._signing_key(token),
                algorithms=self.algorithms,
                audience=self.audiences,
                issuer=self.issuers,
                options={"require": ["exp", "iss", "aud"]},
            )
        except (jwt.PyJWTError, ValueError):
            return None

        client_id = str(claims.get("azp") or claims.get("appid") or "")
        if self.allowed_client_ids is not None and client_id not in self.allowed_client_ids:
            return None

        aud = claims["aud"]
        resource = aud if isinstance(aud, str) else next((a for a in aud if a in self.audiences), None)
        scopes = claims.get("scp", "")
        return AccessToken(
            token=token,
            client_id=client_id,
            scopes=scopes.split() if isinstance(scopes, str) else list(scopes),
            expires_at=claims.get("exp"),
            resource=resource,
            subject=str(claims.get("oid") or claims.get("sub") or ""),
            claims=claims,
        )


def verifier_from_env(env: dict[str, str] | None = None) -> JwtTokenVerifier:
    """The verifier both front doors use (MCP server and REST API), configured from:
    XVA_OAUTH_ISSUER (comma-separated; the first is advertised), XVA_OAUTH_AUDIENCE (comma-separated,
    one per front end), XVA_OAUTH_JWKS_URL and optionally XVA_ALLOWED_CLIENT_IDS (comma-separated)."""
    import os

    env = dict(os.environ) if env is None else env
    return JwtTokenVerifier(
        issuers=env["XVA_OAUTH_ISSUER"],
        audiences=env["XVA_OAUTH_AUDIENCE"],
        jwks_url=env["XVA_OAUTH_JWKS_URL"],
        allowed_client_ids=env.get("XVA_ALLOWED_CLIENT_IDS"),
    )


def required_scopes(env: dict[str, str] | None = None) -> list[str]:
    import os

    env = dict(os.environ) if env is None else env
    return env.get("XVA_REQUIRED_SCOPES", "xva.read").split()

